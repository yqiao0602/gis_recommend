def main():
    pool = json.load(open(POOL, encoding="utf-8"))
    rows = []
    for pr in pool["rows"]:
        lid = pr["line_id"]
        g = G[lid]
        rows.append({
            "line_id": lid, "group": "A", "split": pr["split"],
            "task_type": pr["task_type"], "eligibility_status": pr["status"],
            "task_text": pr["instruction"],   # verbatim from frozen pool
            "task_sha256": hashlib.sha256(pr["instruction"].encode("utf-8")).hexdigest(),
            "required_outcome": g["o"],
            "required_constraints": g["c"],   # [EXPLICIT]/[IMPLICIT] tagged
            "required_capabilities": g["cap"],
            "acceptable_alternatives": g["alt"],
            "failure_conditions": g["f"],
            "underdetermined_aspects": g["u"],
            "presentation_requirements": g["pres"],
            "gold_chain_audit": "PENDING-STAGE-2-STYLE (chains-as-reference only; A-group chains are GEE reference, never gold source)",
            "evidence": g["ev"],
        })
    assert len(rows) == 20 and set(G) == {r["line_id"] for r in rows}
    payload = {"_meta": {
        "stage": "PCA Stage-3 A-group gold worksheet v1 (round-11 approved; round-10 five boundaries applied)",
        "pool_frozen_sha256_prefix": "b5902bbdb93001ba",
        "schema": "B-group compatible + presentation_requirements + [EXPLICIT]/[IMPLICIT] constraint tagging (round-11 boundary 2)",
        "authoring_discipline": "constraints from task text only; no invented numeric params; "
                                "presentation separated; info symmetry respected (reference chain not a gold source)",
        "n_rows": len(rows)},
        "rows": rows}
    blob = json.dumps(payload, ensure_ascii=False, indent=1)
    open(OUT, "w", encoding="utf-8", newline="").write(blob)
    print("rows:", len(rows), "| file_sha256:", hashlib.sha256(blob.encode()).hexdigest()[:16])

if __name__ == "__main__":
    main()
