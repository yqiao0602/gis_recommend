#!/usr/bin/env python3
"""Build domain_corpus_v1 (Phase 1): D3-code + D4-text + D1-anchor pools.

Owner-approved recipe (2026-09-14, option b): D3 code corpus as the main body,
D4 English GIS text as the core semantic supplement, D1 as small domain
anchors; D5 excluded (TAPT candidate only). The final sampling ratio is NOT
pre-fixed — it is decided from the real token census and frozen in the
manifest, with actual per-pool token exposure recorded.

Pipeline (per spec docs/plans/domain_corpus_v1_spec.md §11 Phase 1):
  source SHA exclusion (benchmark candidates superset + paper_v1 val/test)
    -> autogenerated detection
    -> license-header strip
    -> content dedup (exact SHA)
    -> language pooling (code_en / code_mixed; D4 English pool)
    -> L3-structure exclusion
    -> 6-gram leakage exclusion (vs benchmark tasks + paper_v1 val/test)
    -> docstring extraction (D4-doc) + same-dir README (D4-readme)
    -> real tokenizer census (bert-base-uncased wordpiece + bytes + chars)
    -> serialized JSONL pools + manifest + assertion battery

Raw scale is NOT the target: no filter is relaxed to reach a token number.
Run on the compute server (reads /home/yll read-only; writes only under
--out-dir). No training, no authority/evaluation/checkpoint modification.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import re
import sys
import time
from collections import Counter
from pathlib import Path

CJK_RANGES = ((0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF))
L3_CODE_RE = re.compile(r"L3_\d{2}_\d{2}_(?:\d{2}[A-Z]?|[A-Z])")
L3_PAIR_RE = re.compile(r"L3_\d{2}_\d{2}_\w+(?:\s*(?:->|,|;)\s*L3_\d{2}_\d{2}_\w+)+")
AUTOGEN_RE = re.compile(r"auto[- ]?generat|generated by|do not edit|@generated|code generated", re.I)
LICENSE_RE = re.compile(r"copyright|licen[cs]e|spdx|all rights reserved", re.I)
WORD_RE = re.compile(r"[a-z0-9]+")
MIXED_CJK_THRESHOLD = 0.20
MIN_CODE_BYTES = 50
README_MAX_BYTES = 512 * 1024


def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def cjk_ratio(text: str) -> float:
    n_cjk = sum(1 for c in text if any(lo <= ord(c) <= hi for lo, hi in CJK_RANGES))
    n_ns = sum(1 for c in text if not c.isspace())
    return n_cjk / n_ns if n_ns else 0.0


def text_6grams(text: str) -> set:
    w = WORD_RE.findall(text.lower())
    return {" ".join(w[i:i + 6]) for i in range(max(len(w) - 5, 0))}


def strip_license_header(lines: list) -> tuple:
    """Strip a contiguous leading comment block that carries license markers."""
    out, stripped, i = [], 0, 0
    while i < len(lines) and i < 40:
        ln = lines[i].rstrip()
        s = ln.lstrip()
        if s.startswith("#") and LICENSE_RE.search(s):
            stripped += len(ln) + 1
            i += 1
            continue
        if i == 0 and ln.startswith('"""'):
            # leading module docstring that is only a license notice
            j = lines[0].count('"""')
            if j >= 2 and LICENSE_RE.search(lines[0]) and len(lines) > 1 and lines[1].lstrip().startswith(("import", "from", "def", "class", "#")):
                stripped += len(lines[0]) + 1
                i = 1
                continue
        break
    out = lines[i:]
    return out, stripped


def extract_docstrings(code: str) -> list:
    """Module/class/function docstrings via ast (falls back to none on error)."""
    try:
        tree = ast.parse(code)
    except (SyntaxError, ValueError, RecursionError):
        return []
    docs, seen = [], set()
    nodes = [tree] + [n for n in ast.walk(tree)
                      if isinstance(n, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef))]
    for node in nodes:
        if (node.body and isinstance(node.body[0], ast.Expr)
                and isinstance(node.body[0].value, ast.Constant)
                and isinstance(node.body[0].value.value, str)):
            d = node.body[0].value.value.strip()
            if len(d) >= 20 and d not in seen and "copyright" not in d.lower()[:200]:
                seen.add(d)
                docs.append(d)
    return docs


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ledger", type=Path, required=True,
                    help="normalized asset ledger JSONL (47,852 rows with source_path/sha)")
    ap.add_argument("--exclusion", type=Path, required=True, help="JSON list of excluded SHAs")
    ap.add_argument("--grams", type=Path, required=True, help="JSON list of leak 6-grams")
    ap.add_argument("--taxonomy", type=Path, required=True, help="taxonomy_128_v1.json")
    ap.add_argument("--out-dir", type=Path, required=True)
    ap.add_argument("--skip-census", action="store_true", help="skip wordpiece census (bytes only)")
    args = ap.parse_args()

    t0 = time.time()
    args.out_dir.mkdir(parents=True, exist_ok=True)

    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

    excl = set(json.loads(args.exclusion.read_text(encoding="utf-8")))
    leak_grams = set(json.loads(args.grams.read_text(encoding="utf-8")))
    taxonomy = json.loads(args.taxonomy.read_text(encoding="utf-8"))["classes"]
    whitelist_l3 = {c["l3_code"] for c in taxonomy}
    print(f"[load] exclusion SHAs={len(excl)} leak 6-grams={len(leak_grams)} taxonomy={len(taxonomy)}")

    # ── ledger: unique sources (sha, asset_type, path) ──
    sources, seen_sha = {}, set()
    with open(args.ledger, encoding="utf-8") as f:
        for line in f:
            r = json.loads(line)
            sha = r["source_sha256"]
            if sha in seen_sha:
                continue
            seen_sha.add(sha)
            sources[sha] = (r["asset_type"], r["source_path"])
    print(f"[ledger] unique sources={len(sources)}")

    ledger = {
        "schema": "gis_recommend.domain_corpus_v1.build_ledger.v1",
        "input_ledger": str(args.ledger),
        "unique_sources": len(sources),
        "excluded_by_sha": 0,
        "rejected": Counter(),
        "dedup_content": 0,
        "leakage_hits_6gram": 0,
        "l3_structure_hits": 0,
        "docstrings_extracted": 0,
        "readmes_found": 0,
    }

    # ── Stage A: SHA exclusion ──
    work = []
    for sha, (atype, path) in sources.items():
        if sha in excl:
            ledger["excluded_by_sha"] += 1
            continue
        work.append((sha, atype, path))
    print(f"[stage A] excluded_by_sha={ledger['excluded_by_sha']} workset={len(work)}")

    # ── Stage B: per-file processing ──
    d3_rows, d4doc_rows, readme_cache = [], {}, {}
    content_seen = set()
    readme_seen = set()
    leak_hits_detail = []

    for idx, (sha, atype, path) in enumerate(work):
        if idx % 5000 == 0:
            print(f"[stage B] {idx}/{len(work)} ({time.time()-t0:.0f}s)")
        try:
            raw = Path(path).read_bytes()
        except OSError:
            ledger["rejected"]["read_error"] += 1
            continue
        try:
            text = raw.decode("utf-8")
        except UnicodeDecodeError:
            try:
                text = raw.decode("latin-1")
            except Exception:
                ledger["rejected"]["decode_error"] += 1
                continue

        head = "\n".join(text.splitlines()[:10])
        if AUTOGEN_RE.search(head):
            ledger["rejected"]["autogenerated"] += 1
            continue

        lines = text.splitlines(keepends=True)
        lines, stripped = strip_license_header(lines)
        code = "".join(lines)
        if len(code.encode("utf-8", errors="ignore")) < MIN_CODE_BYTES:
            ledger["rejected"]["too_small"] += 1
            continue

        # content-level exact dedup
        csha = sha256_bytes(code.encode("utf-8", errors="ignore"))
        if csha in content_seen:
            ledger["dedup_content"] += 1
            continue
        content_seen.add(csha)

        # L3-structure exclusion (D3/D4 must carry no L3 codes)
        l3_hits = L3_CODE_RE.findall(code)
        if l3_hits:
            ledger["l3_structure_hits"] += 1
            continue

        # 6-gram leakage (fail-closed: drop whole file, record)
        if text_6grams(code) & leak_grams:
            ledger["leakage_hits_6gram"] += 1
            leak_hits_detail.append(path)
            continue

        ratio = cjk_ratio(code)
        pool = "code_mixed" if ratio > MIXED_CJK_THRESHOLD else "code_en"
        d3_rows.append({
            "sha256": sha, "content_sha256": csha, "asset_type": atype,
            "path": path, "pool": pool,
            "bytes": len(code.encode("utf-8", errors="ignore")),
            "cjk_ratio": round(ratio, 3), "license_bytes_stripped": stripped,
            "text": code,
        })

        # docstrings -> D4-doc (English pool)
        for d in extract_docstrings(code):
            ledger["docstrings_extracted"] += 1
            if cjk_ratio(d) > MIXED_CJK_THRESHOLD:
                continue
            if L3_CODE_RE.search(d) or (text_6grams(d) & leak_grams):
                ledger["leakage_hits_6gram"] += 1
                continue
            dsha = sha256_bytes(d.encode("utf-8"))
            if dsha in content_seen:
                continue
            content_seen.add(dsha)
            d4doc_rows.setdefault(dsha, {
                "sha256": dsha, "pool": "doc_en", "origin_sha": sha,
                "bytes": len(d.encode("utf-8")), "text": d})

    # ── README association (same dir as authority sources) ──
    d4readme_rows = {}
    dirs = sorted({str(Path(p).parent) for _, _, p in work})
    print(f"[stage B2] scanning {len(dirs)} dirs for READMEs")
    for d in dirs:
        try:
            entries = list(Path(d).iterdir())
        except OSError:
            continue
        for e in entries:
            if not e.name.lower().startswith("readme"):
                continue
            try:
                rsha = sha256_bytes(e.read_bytes()[:README_MAX_BYTES])
            except OSError:
                continue
            if rsha in readme_seen:
                continue
            readme_seen.add(rsha)
            ledger["readmes_found"] += 1
            try:
                text = e.read_bytes()[:README_MAX_BYTES].decode("utf-8")
            except UnicodeDecodeError:
                continue
            if L3_CODE_RE.search(text) or (text_6grams(text) & leak_grams):
                ledger["leakage_hits_6gram"] += 1
                continue
            ratio = cjk_ratio(text)
            if ratio > MIXED_CJK_THRESHOLD:
                pool = "readme_mixed"
            else:
                pool = "readme_en"
            d4readme_rows[rsha] = {
                "sha256": rsha, "pool": pool, "path": str(e),
                "bytes": len(text.encode("utf-8", errors="ignore")),
                "cjk_ratio": round(ratio, 3), "text": text}

    # ── D1 anchors: taxonomy 128 (name + description; single code anchors allowed) ──
    d1_rows = [{
        "l3_code": c["l3_code"], "name": c["l3_name"],
        "text": f'{c["l3_name"]}: {c["l3_description"]}',
        "bytes": len(f'{c["l3_name"]}: {c["l3_description"]}'.encode("utf-8")),
    } for c in taxonomy]

    # ── write pools ──
    def write_pool(name: str, rows: list) -> Path:
        p = args.out_dir / name
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            for r in rows:
                f.write(json.dumps(r, ensure_ascii=False, sort_keys=True) + "\n")
        return p

    pools = {
        "d3_code.jsonl": d3_rows,
        "d4_docstrings.jsonl": list(d4doc_rows.values()),
        "d4_readmes.jsonl": list(d4readme_rows.values()),
        "d1_anchors.jsonl": d1_rows,
    }
    pool_files = {n: write_pool(n, r) for n, r in pools.items()}
    print(f"[write] {[(n, len(r)) for n, r in pools.items()]}")

    # ── Stage C: census ──
    census = {"bytes": {}, "chars": {}, "docs": {}, "wordpiece_tokens": {}}
    for n, rows in pools.items():
        census["docs"][n] = len(rows)
        census["bytes"][n] = sum(r["bytes"] for r in rows)
        census["chars"][n] = sum(len(r["text"]) for r in rows)
    if not args.skip_census:
        from transformers import AutoTokenizer
        tok = AutoTokenizer.from_pretrained("bert-base-uncased")
        for n, rows in pools.items():
            total = 0
            for i in range(0, len(rows), 64):
                batch = [r["text"][:100_000] for r in rows[i:i + 64]]
                enc = tok(batch, add_special_tokens=False)
                total += sum(len(x) for x in enc["input_ids"])
            census["wordpiece_tokens"][n] = total
            print(f"[census] {n}: docs={census['docs'][n]} bytes={census['bytes'][n]} "
                  f"wordpiece={total}")

    # pool-level language distribution for D3
    lang_dist = Counter(r["pool"] for r in d3_rows)
    asset_dist = Counter(r["asset_type"] for r in d3_rows)

    # ── Stage D: assertion battery ──
    assertions = {}
    assertions["excluded_sha_not_in_corpus"] = not ({r["sha256"] for r in d3_rows} & excl)
    all_d34_text = [r["text"] for r in d3_rows] + \
        [r["text"] for r in d4doc_rows.values()] + [r["text"] for r in d4readme_rows.values()]
    assertions["l3_codes_absent_in_d3_d4"] = not any(L3_CODE_RE.search(t) for t in all_d34_text)
    d1_codes = {r["l3_code"] for r in d1_rows}
    assertions["d1_codes_within_whitelist"] = d1_codes <= whitelist_l3 and len(d1_codes) == 128
    assertions["no_task_to_l3_pair_pattern"] = not any(
        L3_PAIR_RE.search(t) for t in all_d34_text + [r["text"] for r in d1_rows])
    # leakage re-verified on final corpus (sampled full scan)
    assertions["six_gram_zero_on_final"] = not any(
        text_6grams(t) & leak_grams for t in all_d34_text)
    assertions["d5_train_texts_absent_by_construction"] = (
        "paper_v1 train task texts are never read by this build (inputs are the asset "
        "ledger + taxonomy only); structural guarantee")
    assertions["no_frozen_artifact_modified"] = (
        "/home/yll read-only; outputs only under " + str(args.out_dir))

    # ── manifest ──
    d3_tok = census["wordpiece_tokens"].get("d3_code.jsonl", 0)
    d4_tok = (census["wordpiece_tokens"].get("d4_docstrings.jsonl", 0)
              + census["wordpiece_tokens"].get("d4_readmes.jsonl", 0))
    d1_tok = census["wordpiece_tokens"].get("d1_anchors.jsonl", 0)
    total_tok = d3_tok + d4_tok + d1_tok
    exposure = {
        "d3_tokens": d3_tok, "d4_tokens": d4_tok, "d1_tokens": d1_tok,
        "natural_ratio_d3_d4_d1": [round(d3_tok / max(total_tok, 1), 4),
                                   round(d4_tok / max(total_tok, 1), 4),
                                   round(d1_tok / max(total_tok, 1), 4)],
        "target_band_proposal": "D3 70-80% / D4 20-30% / D1 small — requires D4 "
                                "oversampling (or D3 downsampling); owner decision pending",
    }
    manifest = {
        "schema": "gis_recommend.domain_corpus_v1.manifest.v1",
        "corpus_version": "v1",
        "built_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        "recipe": "D3 main body + D4 English GIS text supplement + D1 small anchors "
                  "(owner option b, 2026-09-14); ratio NOT pre-fixed, decided from census",
        "inputs": {k: {"path": str(v), "sha256": sha256_bytes(Path(v).read_bytes()[:1 << 30])}
                   for k, v in dict(ledger_in=args.ledger, exclusion=args.exclusion,
                                    grams=args.grams, taxonomy=args.taxonomy).items()},
        "counts": {
            "sources_unique": len(sources),
            "excluded_by_sha": ledger["excluded_by_sha"],
            "workset": len(work),
            "rejected": dict(ledger["rejected"]),
            "dedup_content": ledger["dedup_content"],
            "leakage_hits_6gram": ledger["leakage_hits_6gram"],
            "l3_structure_hits": ledger["l3_structure_hits"],
            "docstrings_extracted": ledger["docstrings_extracted"],
            "readmes_found": ledger["readmes_found"],
            "docs_per_pool": census["docs"],
        },
        "census": census,
        "d3_language_distribution": dict(lang_dist),
        "d3_asset_type_distribution": dict(asset_dist),
        "final_training_tokens": total_tok,
        "exposure_ratio": exposure,
        "source_sha_coverage": "all 47,852 authority SHAs processed; "
                               f"{len(d3_rows)} admitted to D3 after filters",
        "assertions": assertions,
        "notes": [
            "No filter was relaxed to reach a token target.",
            "D5 (paper_v1 train task texts) is not part of this corpus.",
            "plugin/tutorial metadata (2,009/851) deferred to a possible v1.1.",
            "KG node descriptions deferred (local Neo4j not running at build time).",
        ],
    }
    (args.out_dir / "manifest_v1.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    (args.out_dir / "build_ledger_v1.json").write_text(
        json.dumps(ledger, indent=2, ensure_ascii=False), encoding="utf-8")
    if leak_hits_detail:
        (args.out_dir / "leakage_hits_v1.json").write_text(
            json.dumps(leak_hits_detail, ensure_ascii=False, indent=2), encoding="utf-8")

    # hash ledger of outputs
    with open(args.out_dir / "hash_ledger_v1.json", "w", encoding="utf-8") as f:
        json.dump({n: sha256_bytes(p.read_bytes()) for n, p in pool_files.items()},
                  f, indent=2)

    ok = all(v is True for k, v in assertions.items() if isinstance(v, bool))
    print(f"\n[assertions] {'ALL PASS' if ok else 'FAILURE'}")
    for k, v in assertions.items():
        print(f"  {k}: {v}")
    print(f"\n[manifest] tokens d3={d3_tok} d4={d4_tok} d1={d1_tok} total={total_tok}")
    print(f"natural exposure ratio (d3,d4,d1): {exposure['natural_ratio_d3_d4_d1']}")
    print(f"minutes: {(time.time() - t0) / 60:.1f}")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
