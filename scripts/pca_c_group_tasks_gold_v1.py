def main():
    rows = []
    for t in TASKS:
        r = dict(t)
        r["task_sha256"] = hashlib.sha256(t["task_text"].encode()).hexdigest()
        rows.append(r)
    assert len(rows) == 20
    from collections import Counter
    cells = Counter(r["coverage_cell"] for r in rows)
    assert all(v >= 2 for v in cells.values()), cells
    payload = {"_meta": {
        "stage": "PCA Stage-3 C-group tasks + independent gold v1",
        "independence": "tasks freshly drafted (no reference chains exist); gold derived from task text only",
        "design": "goal-oriented moderate-info texts — scores reflect planning, not constraint-following",
        "coverage_cells": dict(cells),
        "schema": "A-group compatible ([EXPLICIT]/[IMPLICIT], presentation, underdetermined, three calibers)",
        "n_rows": len(rows)},
        "rows": rows}
    blob = json.dumps(payload, ensure_ascii=False, indent=1)
    open(OUT, "w", encoding="utf-8", newline="").write(blob)
    print("rows:", len(rows), "| cells:", dict(cells))
    print("file_sha256:", hashlib.sha256(blob.encode()).hexdigest()[:16])

if __name__ == "__main__":
    main()
